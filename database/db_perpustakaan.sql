CREATE TABLE IF NOT EXISTS buku (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn VARCHAR(32) UNIQUE,
  judul VARCHAR(255) NOT NULL,
  pengarang VARCHAR(255) NOT NULL DEFAULT '',
  penerbit VARCHAR(255),
  tahun_terbit SMALLINT,
  jenis_bahan VARCHAR(30) NOT NULL DEFAULT 'buku',
  kategori VARCHAR(120),
  subjek TEXT,
  nomor_panggil VARCHAR(80),
  lokasi_rak VARCHAR(160),
  deskripsi TEXT,
  url_sampul TEXT,
  total_eksemplar INTEGER NOT NULL DEFAULT 0 CHECK (total_eksemplar >= 0),
  eksemplar_tersedia INTEGER NOT NULL DEFAULT 0 CHECK (eksemplar_tersedia >= 0),
  jumlah_peminjaman INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_peminjaman >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sumber_perolehan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(180) NOT NULL,
  alamat TEXT NOT NULL DEFAULT '',
  telepon VARCHAR(40) NOT NULL DEFAULT '',
  jumlah_eksemplar INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_eksemplar >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS akuisisi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_buku BIGINT NOT NULL REFERENCES buku(id) ON DELETE CASCADE,
  id_sumber_perolehan BIGINT REFERENCES sumber_perolehan(id) ON DELETE SET NULL,
  jenis_rekaman VARCHAR(12) NOT NULL DEFAULT 'standard'
    CHECK (jenis_rekaman IN ('standard', 'rda')),
  nomor_induk VARCHAR(80) NOT NULL DEFAULT '',
  kode_batang VARCHAR(80) NOT NULL DEFAULT '',
  rfid VARCHAR(80) NOT NULL DEFAULT '',
  tanggal_perolehan DATE NOT NULL DEFAULT CURRENT_DATE,
  jumlah INTEGER NOT NULL DEFAULT 1 CHECK (jumlah > 0),
  bentuk_fisik VARCHAR(80) NOT NULL DEFAULT 'Buku',
  jenis_akses VARCHAR(80) NOT NULL DEFAULT 'Dapat dipinjam',
  lokasi VARCHAR(160) NOT NULL DEFAULT '',
  status_koleksi VARCHAR(20) NOT NULL DEFAULT 'in_stock'
    CHECK (status_koleksi IN ('in_stock', 'basket', 'quarantine', 'shipped')),
  metadata_rda JSONB NOT NULL DEFAULT '{}'::jsonb,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS jilid_koleksi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_buku BIGINT NOT NULL REFERENCES buku(id) ON DELETE CASCADE,
  tahun_jilid SMALLINT NOT NULL CHECK (tahun_jilid BETWEEN 1000 AND 9999),
  nomor_jilid VARCHAR(80) NOT NULL DEFAULT '',
  jumlah INTEGER NOT NULL DEFAULT 1 CHECK (jumlah > 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS judul_terbitan_berkala (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bibid VARCHAR(80) NOT NULL UNIQUE,
  judul VARCHAR(500) NOT NULL,
  pengarang VARCHAR(255) NOT NULL DEFAULT '',
  tempat_terbit VARCHAR(180) NOT NULL DEFAULT '',
  penerbit VARCHAR(255) NOT NULL DEFAULT '',
  tahun_terbit SMALLINT CHECK (tahun_terbit BETWEEN 1000 AND 9999),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS edisi_terbitan_berkala (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_terbitan_berkala BIGINT NOT NULL REFERENCES judul_terbitan_berkala(id) ON DELETE CASCADE,
  volume VARCHAR(80) NOT NULL DEFAULT '',
  nomor_edisi VARCHAR(80) NOT NULL DEFAULT '',
  tanggal_terbit DATE,
  tanggal_diterima DATE NOT NULL DEFAULT CURRENT_DATE,
  eksemplar INTEGER NOT NULL DEFAULT 1 CHECK (eksemplar > 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usulan_koleksi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(255) NOT NULL,
  pengarang VARCHAR(255) NOT NULL DEFAULT '',
  penerbit VARCHAR(255) NOT NULL DEFAULT '',
  pengusul VARCHAR(150) NOT NULL DEFAULT '',
  nomor_anggota VARCHAR(80) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'acquired')),
  waktu_diusulkan TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS pengiriman_koleksi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tujuan VARCHAR(180) NOT NULL,
  waktu_dikirim TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status VARCHAR(20) NOT NULL DEFAULT 'sent'
    CHECK (status IN ('sent', 'received')),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS rincian_pengiriman_koleksi (
  id_pengiriman BIGINT NOT NULL REFERENCES pengiriman_koleksi(id) ON DELETE CASCADE,
  id_akuisisi BIGINT NOT NULL REFERENCES akuisisi(id) ON DELETE RESTRICT,
  PRIMARY KEY (id_pengiriman, id_akuisisi)
);

CREATE TABLE IF NOT EXISTS katalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_buku BIGINT REFERENCES buku(id) ON DELETE SET NULL,
  bibid VARCHAR(80) NOT NULL UNIQUE,
  jenis_rekaman VARCHAR(12) NOT NULL DEFAULT 'standard'
    CHECK (jenis_rekaman IN ('standard', 'rda')),
  jenis_bahan VARCHAR(60) NOT NULL DEFAULT 'Monograf',
  judul VARCHAR(500) NOT NULL,
  anak_judul VARCHAR(500) NOT NULL DEFAULT '',
  pernyataan_tanggung_jawab VARCHAR(500) NOT NULL DEFAULT '',
  pencipta VARCHAR(500) NOT NULL DEFAULT '',
  edisi VARCHAR(255) NOT NULL DEFAULT '',
  pernyataan_penerbitan VARCHAR(500) NOT NULL DEFAULT '',
  deskripsi_fisik VARCHAR(500) NOT NULL DEFAULT '',
  subjek TEXT NOT NULL DEFAULT '',
  nomor_panggil VARCHAR(120) NOT NULL DEFAULT '',
  isbn VARCHAR(32) NOT NULL DEFAULT '',
  url_konten_digital TEXT NOT NULL DEFAULT '',
  data_marc JSONB NOT NULL DEFAULT '[]'::jsonb,
  data_rda JSONB NOT NULL DEFAULT '{}'::jsonb,
  status_koleksi VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (status_koleksi IN ('active', 'basket', 'quarantine')),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS konten_digital_katalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_katalog BIGINT NOT NULL REFERENCES katalog(id) ON DELETE CASCADE,
  nama_berkas VARCHAR(255) NOT NULL,
  tipe_mime VARCHAR(150) NOT NULL,
  ukuran_berkas BIGINT NOT NULL CHECK (ukuran_berkas > 0),
  data_berkas BYTEA NOT NULL,
  waktu_diunggah TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS buku_tidak_tampil_di_katalog (
  id_buku BIGINT PRIMARY KEY REFERENCES buku(id) ON DELETE CASCADE,
  waktu_disembunyikan TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS artikel_katalog (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(500) NOT NULL,
  pencipta VARCHAR(500) NOT NULL DEFAULT '',
  subjek TEXT NOT NULL DEFAULT '',
  edisi_terbitan_berkala VARCHAR(255) NOT NULL DEFAULT '',
  judul_katalog VARCHAR(500) NOT NULL DEFAULT '',
  url_konten_digital TEXT NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS publikasi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(500) NOT NULL,
  para_penulis TEXT NOT NULL,
  prodi VARCHAR(10) NOT NULL,
  jurnal VARCHAR(500),
  tahun_terbit SMALLINT,
  peringkat VARCHAR(40),
  doi VARCHAR(255),
  informasi_volume VARCHAR(255),
  kata_kunci TEXT,
  abstrak TEXT,
  url_berkas TEXT,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS permohonan_layanan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_lengkap VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL,
  telepon VARCHAR(40),
  jenis_layanan VARCHAR(120) NOT NULL,
  pesan TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'completed', 'rejected')),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_books_title ON buku (LOWER(judul));
CREATE INDEX IF NOT EXISTS idx_books_author ON buku (LOWER(pengarang));
CREATE INDEX IF NOT EXISTS idx_books_material_type ON buku (jenis_bahan);
CREATE INDEX IF NOT EXISTS idx_books_loan_count ON buku (jumlah_peminjaman DESC);
CREATE INDEX IF NOT EXISTS idx_acquisitions_status_date ON akuisisi (status_koleksi, tanggal_perolehan DESC);
CREATE INDEX IF NOT EXISTS idx_acquisitions_source ON akuisisi (id_sumber_perolehan);
CREATE UNIQUE INDEX IF NOT EXISTS idx_acquisitions_barcode ON akuisisi (kode_batang) WHERE kode_batang <> '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_acquisitions_accession ON akuisisi (nomor_induk) WHERE nomor_induk <> '';
CREATE INDEX IF NOT EXISTS idx_catalog_records_status ON katalog (status_koleksi, judul);
CREATE INDEX IF NOT EXISTS idx_catalog_digital_record ON konten_digital_katalog (id_katalog);
CREATE INDEX IF NOT EXISTS idx_catalog_hidden_books_hidden_at ON buku_tidak_tampil_di_katalog (waktu_disembunyikan);
CREATE INDEX IF NOT EXISTS idx_catalog_articles_title ON artikel_katalog (judul);
CREATE INDEX IF NOT EXISTS idx_periodical_issues_received ON edisi_terbitan_berkala (tanggal_diterima DESC);
CREATE INDEX IF NOT EXISTS idx_collection_proposals_status ON usulan_koleksi (status, waktu_diusulkan DESC);
CREATE INDEX IF NOT EXISTS idx_publications_prodi ON publikasi (prodi);
CREATE INDEX IF NOT EXISTS idx_publications_year ON publikasi (tahun_terbit DESC);
CREATE INDEX IF NOT EXISTS idx_service_requests_status ON permohonan_layanan (status);
CREATE INDEX IF NOT EXISTS idx_service_requests_created_at ON permohonan_layanan (waktu_dibuat DESC);

