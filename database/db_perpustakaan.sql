CREATE TABLE IF NOT EXISTS books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn VARCHAR(32) UNIQUE,
  title VARCHAR(255) NOT NULL,
  author VARCHAR(255) NOT NULL DEFAULT '',
  publisher VARCHAR(255),
  publication_year SMALLINT,
  material_type VARCHAR(30) NOT NULL DEFAULT 'buku',
  category VARCHAR(120),
  subject TEXT,
  call_number VARCHAR(80),
  shelf_location VARCHAR(160),
  description TEXT,
  cover_url TEXT,
  total_copies INTEGER NOT NULL DEFAULT 0 CHECK (total_copies >= 0),
  available_copies INTEGER NOT NULL DEFAULT 0 CHECK (available_copies >= 0),
  loan_count INTEGER NOT NULL DEFAULT 0 CHECK (loan_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS acquisition_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  address TEXT NOT NULL DEFAULT '',
  phone VARCHAR(40) NOT NULL DEFAULT '',
  exemplar_count INTEGER NOT NULL DEFAULT 0 CHECK (exemplar_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS acquisitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  source_id BIGINT REFERENCES acquisition_sources(id) ON DELETE SET NULL,
  record_type VARCHAR(12) NOT NULL DEFAULT 'standard'
    CHECK (record_type IN ('standard', 'rda')),
  accession_no VARCHAR(80) NOT NULL DEFAULT '',
  barcode VARCHAR(80) NOT NULL DEFAULT '',
  rfid VARCHAR(80) NOT NULL DEFAULT '',
  acquisition_date DATE NOT NULL DEFAULT CURRENT_DATE,
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  physical_form VARCHAR(80) NOT NULL DEFAULT 'Buku',
  access_type VARCHAR(80) NOT NULL DEFAULT 'Dapat dipinjam',
  location VARCHAR(160) NOT NULL DEFAULT '',
  lifecycle_status VARCHAR(20) NOT NULL DEFAULT 'in_stock'
    CHECK (lifecycle_status IN ('in_stock', 'basket', 'quarantine', 'shipped')),
  rda_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS collection_bindings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  binding_year SMALLINT NOT NULL CHECK (binding_year BETWEEN 1000 AND 9999),
  volume_number VARCHAR(80) NOT NULL DEFAULT '',
  quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS periodical_titles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bibid VARCHAR(80) NOT NULL UNIQUE,
  title VARCHAR(500) NOT NULL,
  author VARCHAR(255) NOT NULL DEFAULT '',
  publication_place VARCHAR(180) NOT NULL DEFAULT '',
  publisher VARCHAR(255) NOT NULL DEFAULT '',
  publication_year SMALLINT CHECK (publication_year BETWEEN 1000 AND 9999),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS periodical_issues (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodical_id BIGINT NOT NULL REFERENCES periodical_titles(id) ON DELETE CASCADE,
  volume VARCHAR(80) NOT NULL DEFAULT '',
  issue_number VARCHAR(80) NOT NULL DEFAULT '',
  publication_date DATE,
  received_date DATE NOT NULL DEFAULT CURRENT_DATE,
  copies INTEGER NOT NULL DEFAULT 1 CHECK (copies > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS collection_proposals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  author VARCHAR(255) NOT NULL DEFAULT '',
  publisher VARCHAR(255) NOT NULL DEFAULT '',
  requester VARCHAR(150) NOT NULL DEFAULT '',
  member_number VARCHAR(80) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected', 'acquired')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS acquisition_shipments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  destination VARCHAR(180) NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  status VARCHAR(20) NOT NULL DEFAULT 'sent'
    CHECK (status IN ('sent', 'received')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS acquisition_shipment_items (
  shipment_id BIGINT NOT NULL REFERENCES acquisition_shipments(id) ON DELETE CASCADE,
  acquisition_id BIGINT NOT NULL REFERENCES acquisitions(id) ON DELETE RESTRICT,
  PRIMARY KEY (shipment_id, acquisition_id)
);

CREATE TABLE IF NOT EXISTS catalog_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT REFERENCES books(id) ON DELETE SET NULL,
  bibid VARCHAR(80) NOT NULL UNIQUE,
  record_type VARCHAR(12) NOT NULL DEFAULT 'standard'
    CHECK (record_type IN ('standard', 'rda')),
  material_type VARCHAR(60) NOT NULL DEFAULT 'Monograf',
  title VARCHAR(500) NOT NULL,
  subtitle VARCHAR(500) NOT NULL DEFAULT '',
  responsibility VARCHAR(500) NOT NULL DEFAULT '',
  creator VARCHAR(500) NOT NULL DEFAULT '',
  edition VARCHAR(255) NOT NULL DEFAULT '',
  publication_statement VARCHAR(500) NOT NULL DEFAULT '',
  physical_description VARCHAR(500) NOT NULL DEFAULT '',
  subject TEXT NOT NULL DEFAULT '',
  call_number VARCHAR(120) NOT NULL DEFAULT '',
  isbn VARCHAR(32) NOT NULL DEFAULT '',
  digital_content_url TEXT NOT NULL DEFAULT '',
  marc_data JSONB NOT NULL DEFAULT '[]'::jsonb,
  rda_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  lifecycle_status VARCHAR(20) NOT NULL DEFAULT 'active'
    CHECK (lifecycle_status IN ('active', 'basket', 'quarantine')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog_digital_contents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  catalog_record_id BIGINT NOT NULL REFERENCES catalog_records(id) ON DELETE CASCADE,
  file_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(150) NOT NULL,
  file_size BIGINT NOT NULL CHECK (file_size > 0),
  file_data BYTEA NOT NULL,
  uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog_hidden_books (
  book_id BIGINT PRIMARY KEY REFERENCES books(id) ON DELETE CASCADE,
  hidden_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog_articles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(500) NOT NULL,
  creator VARCHAR(500) NOT NULL DEFAULT '',
  subject TEXT NOT NULL DEFAULT '',
  serial_edition VARCHAR(255) NOT NULL DEFAULT '',
  catalog_title VARCHAR(500) NOT NULL DEFAULT '',
  digital_content_url TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(500) NOT NULL,
  authors TEXT NOT NULL,
  prodi VARCHAR(10) NOT NULL,
  journal VARCHAR(500),
  publication_year SMALLINT,
  ranking VARCHAR(40),
  doi VARCHAR(255),
  volume_info VARCHAR(255),
  keywords TEXT,
  abstract TEXT,
  file_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS service_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(40),
  service_type VARCHAR(120) NOT NULL,
  message TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'in_progress', 'completed', 'rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_books_title ON books (LOWER(title));
CREATE INDEX IF NOT EXISTS idx_books_author ON books (LOWER(author));
CREATE INDEX IF NOT EXISTS idx_books_material_type ON books (material_type);
CREATE INDEX IF NOT EXISTS idx_books_loan_count ON books (loan_count DESC);
CREATE INDEX IF NOT EXISTS idx_acquisitions_status_date ON acquisitions (lifecycle_status, acquisition_date DESC);
CREATE INDEX IF NOT EXISTS idx_acquisitions_source ON acquisitions (source_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_acquisitions_barcode ON acquisitions (barcode) WHERE barcode <> '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_acquisitions_accession ON acquisitions (accession_no) WHERE accession_no <> '';
CREATE INDEX IF NOT EXISTS idx_catalog_records_status ON catalog_records (lifecycle_status, title);
CREATE INDEX IF NOT EXISTS idx_catalog_digital_record ON catalog_digital_contents (catalog_record_id);
CREATE INDEX IF NOT EXISTS idx_catalog_hidden_books_hidden_at ON catalog_hidden_books (hidden_at);
CREATE INDEX IF NOT EXISTS idx_catalog_articles_title ON catalog_articles (title);
CREATE INDEX IF NOT EXISTS idx_periodical_issues_received ON periodical_issues (received_date DESC);
CREATE INDEX IF NOT EXISTS idx_collection_proposals_status ON collection_proposals (status, requested_at DESC);
CREATE INDEX IF NOT EXISTS idx_publications_prodi ON publications (prodi);
CREATE INDEX IF NOT EXISTS idx_publications_year ON publications (publication_year DESC);
CREATE INDEX IF NOT EXISTS idx_service_requests_status ON service_requests (status);
CREATE INDEX IF NOT EXISTS idx_service_requests_created_at ON service_requests (created_at DESC);

