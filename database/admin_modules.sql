BEGIN;

CREATE TABLE IF NOT EXISTS jenis_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO jenis_anggota (name)
VALUES ('Mahasiswa'), ('Dosen'), ('Tenaga Kependidikan'), ('Umum')
ON CONFLICT (name) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS idx_member_types_name_ci
  ON jenis_anggota (LOWER(name));

CREATE TABLE IF NOT EXISTS anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_number VARCHAR(80) NOT NULL UNIQUE,
  member_type_id BIGINT NOT NULL REFERENCES jenis_anggota(id) ON DELETE RESTRICT,
  identity_type VARCHAR(40) NOT NULL DEFAULT 'KTP / NIK',
  identity_number VARCHAR(80),
  full_name VARCHAR(180) NOT NULL,
  birth_place VARCHAR(120),
  birth_date DATE,
  gender VARCHAR(20) CHECK (gender IN ('Laki-laki', 'Perempuan')),
  phone VARCHAR(40),
  email VARCHAR(180),
  address TEXT,
  province VARCHAR(120),
  city VARCHAR(120),
  district VARCHAR(120),
  village VARCHAR(120),
  rt VARCHAR(10),
  rw VARCHAR(10),
  current_address TEXT,
  current_province VARCHAR(120),
  current_city VARCHAR(120),
  work_unit VARCHAR(120),
  faculty VARCHAR(120),
  department VARCHAR(120),
  study_program VARCHAR(120),
  registration_date DATE NOT NULL DEFAULT CURRENT_DATE,
  expiry_date DATE,
  status VARCHAR(24) NOT NULL DEFAULT 'Aktif'
    CHECK (status IN ('Aktif', 'Tidak Aktif', 'Ditangguhkan')),
  registration_fee NUMERIC(12, 2) NOT NULL DEFAULT 0
    CHECK (registration_fee >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (expiry_date IS NULL OR expiry_date >= registration_date)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_members_identity_number
  ON anggota (identity_type, identity_number)
  WHERE identity_number IS NOT NULL AND identity_number <> '';
CREATE INDEX IF NOT EXISTS idx_members_name ON anggota (LOWER(full_name));
CREATE INDEX IF NOT EXISTS idx_members_status_expiry ON anggota (status, expiry_date);

CREATE TABLE IF NOT EXISTS sumbangan_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
  donation_date DATE NOT NULL DEFAULT CURRENT_DATE,
  description VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_membership_donations_member_date
  ON sumbangan_anggota (member_number, donation_date DESC);

CREATE TABLE IF NOT EXISTS perpanjangan_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  fee NUMERIC(12, 2) NOT NULL CHECK (fee >= 0),
  renewal_date DATE NOT NULL DEFAULT CURRENT_DATE,
  expiry_date DATE,
  description VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_membership_renewals_member_date
  ON perpanjangan_anggota (member_number, renewal_date DESC);

CREATE TABLE IF NOT EXISTS keranjang_anggota (
  member_id BIGINT PRIMARY KEY REFERENCES anggota(id) ON DELETE CASCADE,
  added_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS survei (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Draft'
    CHECK (status IN ('Aktif', 'Draft', 'Selesai')),
  sequence_number INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  target INTEGER NOT NULL CHECK (target > 0),
  respondent_count INTEGER NOT NULL DEFAULT 0 CHECK (respondent_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS idx_surveys_status_dates
  ON survei (status, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_surveys_name
  ON survei (LOWER(name));

CREATE TABLE IF NOT EXISTS peminjaman (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_number VARCHAR(80) NOT NULL UNIQUE,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  acquisition_id BIGINT REFERENCES akuisisi(id) ON DELETE SET NULL,
  barcode VARCHAR(80) NOT NULL,
  title VARCHAR(255) NOT NULL,
  publisher VARCHAR(255) NOT NULL DEFAULT '',
  location VARCHAR(180) NOT NULL DEFAULT 'Perpustakaan Pusat',
  loan_date DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date DATE NOT NULL,
  returned_at DATE,
  renewal_count INTEGER NOT NULL DEFAULT 0 CHECK (renewal_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (due_date >= loan_date),
  CHECK (returned_at IS NULL OR returned_at >= loan_date)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_circulation_loans_open_barcode
  ON peminjaman (barcode)
  WHERE returned_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_circulation_loans_member_date
  ON peminjaman (member_number, loan_date DESC);
CREATE INDEX IF NOT EXISTS idx_circulation_loans_due_date
  ON peminjaman (due_date)
  WHERE returned_at IS NULL;

CREATE TABLE IF NOT EXISTS perpanjangan_peminjaman (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL REFERENCES peminjaman(id) ON DELETE RESTRICT,
  renewal_date DATE NOT NULL DEFAULT CURRENT_DATE,
  renewal_count INTEGER NOT NULL CHECK (renewal_count > 0),
  previous_due_date DATE NOT NULL,
  new_due_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (new_due_date > previous_due_date)
);

CREATE INDEX IF NOT EXISTS idx_circulation_renewals_loan_date
  ON perpanjangan_peminjaman (loan_id, renewal_date DESC);

CREATE TABLE IF NOT EXISTS pengembalian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL UNIQUE REFERENCES peminjaman(id) ON DELETE RESTRICT,
  return_date DATE NOT NULL DEFAULT CURRENT_DATE,
  late_days INTEGER NOT NULL DEFAULT 0 CHECK (late_days >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_returns_date
  ON pengembalian (return_date DESC);

CREATE TABLE IF NOT EXISTS reservasi_koleksi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  title VARCHAR(255) NOT NULL,
  publisher VARCHAR(255) NOT NULL DEFAULT '',
  location VARCHAR(180) NOT NULL DEFAULT '',
  reservation_date DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR(24) NOT NULL DEFAULT 'Menunggu'
    CHECK (status IN ('Menunggu', 'Siap Diambil', 'Selesai', 'Dibatalkan')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_reservations_status_date
  ON reservasi_koleksi (status, reservation_date DESC);
CREATE INDEX IF NOT EXISTS idx_circulation_reservations_member
  ON reservasi_koleksi (member_number);

CREATE TABLE IF NOT EXISTS proyek_stok_opname (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_name VARCHAR(180) NOT NULL,
  start_date DATE NOT NULL DEFAULT CURRENT_DATE,
  year SMALLINT NOT NULL CHECK (year BETWEEN 1000 AND 9999),
  coordinator VARCHAR(180) NOT NULL DEFAULT '',
  note VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stock_opname_projects_year
  ON proyek_stok_opname (year DESC, start_date DESC);

CREATE TABLE IF NOT EXISTS pelanggaran_sirkulasi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT REFERENCES peminjaman(id) ON DELETE SET NULL,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  transaction_number VARCHAR(80) NOT NULL DEFAULT '',
  barcode VARCHAR(80) NOT NULL DEFAULT '',
  title VARCHAR(255) NOT NULL DEFAULT '',
  violation_type VARCHAR(120) NOT NULL,
  fine NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (fine >= 0),
  suspension_days INTEGER NOT NULL DEFAULT 0 CHECK (suspension_days >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_violations_member_date
  ON pelanggaran_sirkulasi (member_number, created_at DESC);

CREATE TABLE IF NOT EXISTS koleksi_siap_layan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  responsible VARCHAR(180) NOT NULL DEFAULT '',
  nip VARCHAR(80) NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'Menunggu Verifikasi'
    CHECK (status IN ('Menunggu Verifikasi', 'Siap Layan')),
  verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((status = 'Siap Layan') = (verified_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_ready_service_collections_status
  ON koleksi_siap_layan (status, created_at DESC);

CREATE TABLE IF NOT EXISTS loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  locker_number VARCHAR(80) NOT NULL UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS peminjaman_loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_number VARCHAR(80) NOT NULL UNIQUE,
  locker_id BIGINT REFERENCES loker(id) ON DELETE RESTRICT,
  locker_number VARCHAR(80) NOT NULL,
  member_id BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  member_number VARCHAR(80) NOT NULL,
  full_name VARCHAR(180) NOT NULL,
  guarantee_type VARCHAR(80) NOT NULL,
  guarantee_note VARCHAR(180) NOT NULL DEFAULT '',
  loan_date DATE NOT NULL DEFAULT CURRENT_DATE,
  returned_at DATE,
  violation VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (returned_at IS NULL OR returned_at >= loan_date)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_locker_loans_open_locker
  ON peminjaman_loker (LOWER(locker_number))
  WHERE returned_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_locker_loans_member_date
  ON peminjaman_loker (member_number, loan_date DESC);

CREATE TABLE IF NOT EXISTS pengembalian_loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  locker_loan_id BIGINT NOT NULL UNIQUE REFERENCES peminjaman_loker(id) ON DELETE RESTRICT,
  return_date DATE NOT NULL DEFAULT CURRENT_DATE,
  violation VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_locker_returns_date
  ON pengembalian_loker (return_date DESC);

COMMIT;
