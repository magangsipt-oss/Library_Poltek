BEGIN;

CREATE TABLE IF NOT EXISTS jenis_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(80) NOT NULL UNIQUE,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO jenis_anggota (nama)
VALUES ('Mahasiswa'), ('Dosen'), ('Tenaga Kependidikan'), ('Umum')
ON CONFLICT (nama) DO NOTHING;

CREATE UNIQUE INDEX IF NOT EXISTS idx_member_types_name_ci
  ON jenis_anggota (LOWER(nama));

CREATE TABLE IF NOT EXISTS anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_anggota VARCHAR(80) NOT NULL UNIQUE,
  id_jenis_anggota BIGINT NOT NULL REFERENCES jenis_anggota(id) ON DELETE RESTRICT,
  jenis_identitas VARCHAR(40) NOT NULL DEFAULT 'KTP / NIK',
  nomor_identitas VARCHAR(80),
  nama_lengkap VARCHAR(180) NOT NULL,
  tempat_lahir VARCHAR(120),
  tanggal_lahir DATE,
  jenis_kelamin VARCHAR(20) CHECK (jenis_kelamin IN ('Laki-laki', 'Perempuan')),
  telepon VARCHAR(40),
  email VARCHAR(180),
  alamat TEXT,
  provinsi VARCHAR(120),
  kota VARCHAR(120),
  kecamatan VARCHAR(120),
  kelurahan_desa VARCHAR(120),
  rt VARCHAR(10),
  rw VARCHAR(10),
  alamat_sekarang TEXT,
  provinsi_sekarang VARCHAR(120),
  kota_sekarang VARCHAR(120),
  unit_kerja VARCHAR(120),
  fakultas VARCHAR(120),
  jurusan VARCHAR(120),
  program_studi VARCHAR(120),
  tanggal_pendaftaran DATE NOT NULL DEFAULT CURRENT_DATE,
  tanggal_berakhir DATE,
  status VARCHAR(24) NOT NULL DEFAULT 'Aktif'
    CHECK (status IN ('Aktif', 'Tidak Aktif', 'Ditangguhkan')),
  biaya_pendaftaran NUMERIC(12, 2) NOT NULL DEFAULT 0
    CHECK (biaya_pendaftaran >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (tanggal_berakhir IS NULL OR tanggal_berakhir >= tanggal_pendaftaran)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_members_identity_number
  ON anggota (jenis_identitas, nomor_identitas)
  WHERE nomor_identitas IS NOT NULL AND nomor_identitas <> '';
CREATE INDEX IF NOT EXISTS idx_members_name ON anggota (LOWER(nama_lengkap));
CREATE INDEX IF NOT EXISTS idx_members_status_expiry ON anggota (status, tanggal_berakhir);

CREATE TABLE IF NOT EXISTS sumbangan_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  jumlah_sumbangan NUMERIC(12, 2) NOT NULL CHECK (jumlah_sumbangan >= 0),
  tanggal_sumbangan DATE NOT NULL DEFAULT CURRENT_DATE,
  deskripsi VARCHAR(500) NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_membership_donations_member_date
  ON sumbangan_anggota (nomor_anggota, tanggal_sumbangan DESC);

CREATE TABLE IF NOT EXISTS perpanjangan_anggota (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  biaya NUMERIC(12, 2) NOT NULL CHECK (biaya >= 0),
  tanggal_perpanjangan DATE NOT NULL DEFAULT CURRENT_DATE,
  tanggal_berakhir DATE,
  deskripsi VARCHAR(500) NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_membership_renewals_member_date
  ON perpanjangan_anggota (nomor_anggota, tanggal_perpanjangan DESC);

CREATE TABLE IF NOT EXISTS keranjang_anggota (
  id_anggota BIGINT PRIMARY KEY REFERENCES anggota(id) ON DELETE CASCADE,
  waktu_ditambahkan TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS survei (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(180) NOT NULL,
  tanggal_mulai DATE NOT NULL,
  tanggal_selesai DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Draft'
    CHECK (status IN ('Aktif', 'Draft', 'Selesai')),
  nomor_urut INTEGER GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  target INTEGER NOT NULL CHECK (target > 0),
  jumlah_responden INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_responden >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (tanggal_selesai >= tanggal_mulai)
);

CREATE INDEX IF NOT EXISTS idx_surveys_status_dates
  ON survei (status, tanggal_mulai, tanggal_selesai);
CREATE INDEX IF NOT EXISTS idx_surveys_name
  ON survei (LOWER(nama));

CREATE TABLE IF NOT EXISTS peminjaman (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_transaksi VARCHAR(80) NOT NULL UNIQUE,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  id_akuisisi BIGINT REFERENCES akuisisi(id) ON DELETE SET NULL,
  kode_batang VARCHAR(80) NOT NULL,
  judul VARCHAR(255) NOT NULL,
  penerbit VARCHAR(255) NOT NULL DEFAULT '',
  lokasi VARCHAR(180) NOT NULL DEFAULT 'Perpustakaan Pusat',
  tanggal_peminjaman DATE NOT NULL DEFAULT CURRENT_DATE,
  tanggal_jatuh_tempo DATE NOT NULL,
  tanggal_dikembalikan DATE,
  jumlah_perpanjangan INTEGER NOT NULL DEFAULT 0 CHECK (jumlah_perpanjangan >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (tanggal_jatuh_tempo >= tanggal_peminjaman),
  CHECK (tanggal_dikembalikan IS NULL OR tanggal_dikembalikan >= tanggal_peminjaman)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_circulation_loans_open_barcode
  ON peminjaman (kode_batang)
  WHERE tanggal_dikembalikan IS NULL;
CREATE INDEX IF NOT EXISTS idx_circulation_loans_member_date
  ON peminjaman (nomor_anggota, tanggal_peminjaman DESC);
CREATE INDEX IF NOT EXISTS idx_circulation_loans_due_date
  ON peminjaman (tanggal_jatuh_tempo)
  WHERE tanggal_dikembalikan IS NULL;

CREATE TABLE IF NOT EXISTS perpanjangan_peminjaman (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peminjaman BIGINT NOT NULL REFERENCES peminjaman(id) ON DELETE RESTRICT,
  tanggal_perpanjangan DATE NOT NULL DEFAULT CURRENT_DATE,
  jumlah_perpanjangan INTEGER NOT NULL CHECK (jumlah_perpanjangan > 0),
  tanggal_jatuh_tempo_lama DATE NOT NULL,
  tanggal_jatuh_tempo_baru DATE NOT NULL,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (tanggal_jatuh_tempo_baru > tanggal_jatuh_tempo_lama)
);

CREATE INDEX IF NOT EXISTS idx_circulation_renewals_loan_date
  ON perpanjangan_peminjaman (id_peminjaman, tanggal_perpanjangan DESC);

CREATE TABLE IF NOT EXISTS pengembalian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peminjaman BIGINT NOT NULL UNIQUE REFERENCES peminjaman(id) ON DELETE RESTRICT,
  tanggal_pengembalian DATE NOT NULL DEFAULT CURRENT_DATE,
  hari_keterlambatan INTEGER NOT NULL DEFAULT 0 CHECK (hari_keterlambatan >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_returns_date
  ON pengembalian (tanggal_pengembalian DESC);

CREATE TABLE IF NOT EXISTS reservasi_koleksi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  judul VARCHAR(255) NOT NULL,
  penerbit VARCHAR(255) NOT NULL DEFAULT '',
  lokasi VARCHAR(180) NOT NULL DEFAULT '',
  tanggal_reservasi DATE NOT NULL DEFAULT CURRENT_DATE,
  status VARCHAR(24) NOT NULL DEFAULT 'Menunggu'
    CHECK (status IN ('Menunggu', 'Siap Diambil', 'Selesai', 'Dibatalkan')),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_reservations_status_date
  ON reservasi_koleksi (status, tanggal_reservasi DESC);
CREATE INDEX IF NOT EXISTS idx_circulation_reservations_member
  ON reservasi_koleksi (nomor_anggota);

CREATE TABLE IF NOT EXISTS proyek_stok_opname (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_proyek VARCHAR(180) NOT NULL,
  tanggal_mulai DATE NOT NULL DEFAULT CURRENT_DATE,
  tahun SMALLINT NOT NULL CHECK (tahun BETWEEN 1000 AND 9999),
  koordinator VARCHAR(180) NOT NULL DEFAULT '',
  catatan VARCHAR(500) NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stock_opname_projects_year
  ON proyek_stok_opname (tahun DESC, tanggal_mulai DESC);

CREATE TABLE IF NOT EXISTS pelanggaran_sirkulasi (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peminjaman BIGINT REFERENCES peminjaman(id) ON DELETE SET NULL,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  nomor_transaksi VARCHAR(80) NOT NULL DEFAULT '',
  kode_batang VARCHAR(80) NOT NULL DEFAULT '',
  judul VARCHAR(255) NOT NULL DEFAULT '',
  jenis_pelanggaran VARCHAR(120) NOT NULL,
  denda NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (denda >= 0),
  hari_penangguhan INTEGER NOT NULL DEFAULT 0 CHECK (hari_penangguhan >= 0),
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_circulation_violations_member_date
  ON pelanggaran_sirkulasi (nomor_anggota, waktu_dibuat DESC);

CREATE TABLE IF NOT EXISTS koleksi_siap_layan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  judul VARCHAR(255) NOT NULL,
  penanggung_jawab VARCHAR(180) NOT NULL DEFAULT '',
  nip VARCHAR(80) NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'Menunggu Verifikasi'
    CHECK (status IN ('Menunggu Verifikasi', 'Siap Layan')),
  waktu_diverifikasi TIMESTAMPTZ,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((status = 'Siap Layan') = (waktu_diverifikasi IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_ready_service_collections_status
  ON koleksi_siap_layan (status, waktu_dibuat DESC);

CREATE TABLE IF NOT EXISTS loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_loker VARCHAR(80) NOT NULL UNIQUE,
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS peminjaman_loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor_transaksi VARCHAR(80) NOT NULL UNIQUE,
  id_loker BIGINT REFERENCES loker(id) ON DELETE RESTRICT,
  nomor_loker VARCHAR(80) NOT NULL,
  id_anggota BIGINT REFERENCES anggota(id) ON DELETE RESTRICT,
  nomor_anggota VARCHAR(80) NOT NULL,
  nama_lengkap VARCHAR(180) NOT NULL,
  jenis_jaminan VARCHAR(80) NOT NULL,
  catatan_jaminan VARCHAR(180) NOT NULL DEFAULT '',
  tanggal_peminjaman DATE NOT NULL DEFAULT CURRENT_DATE,
  tanggal_dikembalikan DATE,
  pelanggaran VARCHAR(500) NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  waktu_diperbarui TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (tanggal_dikembalikan IS NULL OR tanggal_dikembalikan >= tanggal_peminjaman)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_locker_loans_open_locker
  ON peminjaman_loker (LOWER(nomor_loker))
  WHERE tanggal_dikembalikan IS NULL;
CREATE INDEX IF NOT EXISTS idx_locker_loans_member_date
  ON peminjaman_loker (nomor_anggota, tanggal_peminjaman DESC);

CREATE TABLE IF NOT EXISTS pengembalian_loker (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_peminjaman_loker BIGINT NOT NULL UNIQUE REFERENCES peminjaman_loker(id) ON DELETE RESTRICT,
  tanggal_pengembalian DATE NOT NULL DEFAULT CURRENT_DATE,
  pelanggaran VARCHAR(500) NOT NULL DEFAULT '',
  waktu_dibuat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_locker_returns_date
  ON pengembalian_loker (tanggal_pengembalian DESC);

COMMIT;
